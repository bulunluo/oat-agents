/// The script a session runs. Both backends start interactive, with the prompt as their
/// first turn: the session has to stay up after that turn for the live view to show it and
/// type at it — `codex exec` would answer once and exit, taking the pane with it.
pub(crate) fn launch_script(backend: Backend) -> String {
    // Inspect only names, and unset in this shell (a piped while loop would use a subshell).
    // Keep credentials out of the generated script and disable tracing before reading them.
    let mut script = String::from(
        r#"#!/bin/sh
# Generated by oat-agents. The agent's prompt is prompt.md beside this file.
set +x
for oat_auth_name in $(env | sed -n 's/^\(CLAUDE_CODE_[A-Za-z0-9_]*\)=.*/\1/p'); do
  unset "$oat_auth_name"
done
unset oat_auth_name
"#,
    );
    // tmux receives explicit empty overrides for unset account variables. Restore absence
    // before starting either backend, matching workspace trust's empty-value fallback.
    for name in ACCOUNT_SCOPE_VARS {
        script.push_str(&format!("[ -n \"${{{name}:-}}\" ] || unset {name}\n"));
    }
    if backend == Backend::Claude {
        script.push_str(r#"if [ "${OAT_CLAUDE_TOKEN_FILE+x}" = x ]; then
  if [ ! -L "$OAT_CLAUDE_TOKEN_FILE" ] &&
     [ -f "$OAT_CLAUDE_TOKEN_FILE" ] && [ -s "$OAT_CLAUDE_TOKEN_FILE" ] &&
     { oat_auth_metadata=$(stat -f '%Lp %u' -- "$OAT_CLAUDE_TOKEN_FILE" 2>/dev/null) ||
       oat_auth_metadata=$(stat -c '%a %u' -- "$OAT_CLAUDE_TOKEN_FILE" 2>/dev/null); } &&
     [ "$oat_auth_metadata" = "600 $(id -u)" ]; then
    export CLAUDE_CODE_OAUTH_TOKEN="$(cat "$OAT_CLAUDE_TOKEN_FILE" 2>/dev/null)"
  else
    printf '%s\n' 'oat-agents: ignoring invalid OAT_CLAUDE_TOKEN_FILE (requires a nonempty owned regular file, not a symlink, with mode 0600)' >&2
  fi
fi
unset oat_auth_metadata
"#);
    }
    script.push_str("cd \"${OAT_WORKTREE:?}\" || exit 1\n");
    script.push_str(match backend {
        Backend::Claude => concat!(
            "exec \"${OAT_CLAUDE_COMMAND:-claude}\" --dangerously-skip-permissions \\\n",
            "  ${OAT_MODEL:+--model \"$OAT_MODEL\"} ${OAT_CLAUDE_ARGS:-} \\\n",
            "  \"$(cat \"${OAT_DISPATCH_DIR:?}/prompt.md\")\"\n",
        ),
        Backend::Codex => concat!(
            "exec \"${OAT_CODEX_COMMAND:-codex}\" --dangerously-bypass-approvals-and-sandbox \\\n",
            "  ${OAT_MODEL:+-m \"$OAT_MODEL\"} ${OAT_EFFORT:+-c model_reasoning_effort=\"$OAT_EFFORT\"} ${OAT_CODEX_ARGS:-} \\\n",
            "  \"$(cat \"${OAT_DISPATCH_DIR:?}/prompt.md\")\"\n",
        ),
    });
    script
}

const PASS_THROUGH_VARS: &[&str] = &[
    "OAT_AGENTS_LOG_DIR",
    "OAT_AGENTS_STATE_DIR",
    "OAT_AGENTS_CHECKLIST_DIR",
    "OAT_TMUX_COMMAND",
    "OAT_TMUX_SOCKET",
    "OAT_CLAUDE_COMMAND",
    "OAT_CODEX_COMMAND",
];

const ACCOUNT_SCOPE_VARS: &[&str] = &[
    "CLAUDE_CONFIG_DIR",
    "OAT_CLAUDE_TOKEN_FILE",
    "CODEX_HOME",
];

/// Override account scope even when absent: otherwise tmux inherits the account that
/// started its shared server. launch.sh turns empty overrides back into unset variables.
pub(crate) fn session_environment(env: &dyn Environment) -> Vec<(String, String)> {
    PASS_THROUGH_VARS
        .iter()
        .filter_map(|name| env.var(name).map(|value| (name.to_string(), value)))
        .chain(ACCOUNT_SCOPE_VARS.iter().map(|name| {
            (name.to_string(), env.var(name).unwrap_or_default())
        }))
        .collect()
}

/// Prepares a Dispatch, starts its tmux session, then records the successful launch.
pub fn launch_dispatch(
    env: &dyn Environment,
    store: &Store,
    log: &EventLog,
    spec: LaunchSpec,
    dispatch_id: String,
    model_env: (Option<String>, Option<String>),
) -> Result<(DispatchRecord, PathBuf)> {
    Tmux::from_env(env).check_available()?;
    let (mut dispatch, dispatch_dir) =
        prepare_dispatch_files(store, &spec, dispatch_id, model_env, false)?;
    if let Err(e) = start_dispatch(env, &spec.run, &dispatch, &dispatch_dir) {
        if spec.created_fresh_worktree {
            let _ = worktree::remove_worktree(
                &spec.repo,
                &spec.worktree,
                &spec.branch,
                &spec.run.base_branch,
                true,
            );
        }
        return Err(e);
    }
    capture_identity(&Tmux::from_env(env), &spec.run, &mut dispatch);
    record_dispatch(store, log, &dispatch)?;
    Ok((dispatch, dispatch_dir))
}

/// Materializes skills, writes `prompt.md` and `launch.sh`, and records the Dispatch,
/// without invoking tmux. On a skill conflict, a fresh worktree is removed so nothing
/// is left half-prepared (ticket §6.2 rule 3).
pub fn prepare_dispatch(
    store: &Store,
    log: &EventLog,
    spec: &LaunchSpec,
    dispatch_id: String,
    model_env: (Option<String>, Option<String>),
    headless: bool,
) -> Result<(DispatchRecord, PathBuf)> {
    let (dispatch, dispatch_dir) =
        prepare_dispatch_files(store, spec, dispatch_id, model_env, headless)?;
    record_dispatch(store, log, &dispatch)?;
    Ok((dispatch, dispatch_dir))
}

/// Writes the launch files without recording a Dispatch or emitting agent_enter.
fn prepare_dispatch_files(
    store: &Store,
    spec: &LaunchSpec,
    dispatch_id: String,
    model_env: (Option<String>, Option<String>),
    headless: bool,
) -> Result<(DispatchRecord, PathBuf)> {
    if let Err(e) = skills::materialize_skills(&spec.worktree, spec.backend, &spec.skills) {
        if spec.created_fresh_worktree {
            let _ = worktree::remove_worktree(
                &spec.repo,
                &spec.worktree,
                &spec.branch,
                &spec.run.base_branch,
                true,
            );
        }
        return Err(e);
    }

    let settle_command = if spec.is_core {
        "meta finish"
    } else {
        "dispatch done"
    };

    let preamble_template = if spec.is_core {
        prompt::PREAMBLE_CORE_ROLE
    } else {
        prompt::PREAMBLE_ROLE
    };

    let known_skills: std::collections::BTreeSet<String> =
        spec.skills.iter().map(|s| s.name.clone()).collect();

    let preamble = prompt::render_preamble(
        preamble_template,
        prompt::PreambleFields {
            role_name: &spec.role_label,
            run_id: &spec.run.id,
            dispatch_id: &dispatch_id,
            backend: spec.backend,
            worktree: &spec.worktree.to_string_lossy(),
            role_names: &spec.role_names_for_preamble,
            settle_command,
        },
        &known_skills,
    );

    let baseline_or_protocol = if spec.is_core {
        spec.baseline.as_str()
    } else {
        prompt::ROLE_PROTOCOL
    };

    let full_prompt = prompt::assemble(
        prompt::PromptParts {
            preamble,
            baseline: baseline_or_protocol,
            instructions: &spec.instructions,
            task: &spec.task,
        },
        spec.backend,
        &known_skills,
    );

    let dispatch_dir = store.dispatch_dir_path(&spec.run.id, &dispatch_id);
    fs::create_dir_all(&dispatch_dir)?;
    fs::write(dispatch_dir.join("prompt.md"), &full_prompt)?;
    let script = launch_script(spec.backend);
    let script_path = dispatch_dir.join("launch.sh");
    fs::write(&script_path, &script)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&script_path, fs::Permissions::from_mode(0o755))?;
    }

    let (model, effort) = model_env;
    let dispatch = DispatchRecord {
        id: dispatch_id.clone(),
        run_id: spec.run.id.clone(),
        role: spec.role_label.clone(),
        backend: format!("{:?}", spec.backend).to_lowercase(),
        worktree: spec.worktree.to_string_lossy().to_string(),
        branch: spec.branch.clone(),
        created_at: now_iso(),
        env_id: None,
        image_id: None,
        env_skipped: None,
        settled: None,
        report: None,
        released_at: None,
        name: spec.name.clone(),
        model,
        effort,
        headless,
        pid: None,
        pgid: None,
        started_at: None,
        identity_warning: None,
        trust_warning: spec.trust_warning.clone(),
    };
    Ok((dispatch, dispatch_dir))
}

fn capture_identity(tmux: &Tmux, run: &RunRecord, dispatch: &mut DispatchRecord) {
    let session = Tmux::session_name(&dispatch.hash_id(run));
    dispatch.pid = tmux.pane_pid(&session);
    let identity = dispatch.pid.ok_or_else(|| anyhow::anyhow!("tmux pane_pid unavailable"))
        .and_then(process_identity);
    match identity {
        Ok((pgid, started_at)) => {
            dispatch.pgid = Some(pgid);
            dispatch.started_at = Some(started_at);
        }
        Err(error) => dispatch.identity_warning = Some(format!("could not capture process identity: {error}")),
    }
}

fn process_identity(pid: u32) -> Result<(u32, String)> {
    let output = std::process::Command::new("ps")
        .args(["-o", "pgid=,lstart=", "-p", &pid.to_string()])
        .env("LC_ALL", "C")
        .output()?;
    anyhow::ensure!(output.status.success(), "ps could not inspect pane pid {pid}");
    parse_process_identity(std::str::from_utf8(&output.stdout)?)
}

fn parse_process_identity(text: &str) -> Result<(u32, String)> {
    let text = text.trim();
    let (pgid, started_at) = text.split_once(char::is_whitespace)
        .ok_or_else(|| anyhow::anyhow!("ps returned no process start time"))?;
    let pgid: u32 = pgid.parse()?;
    let started_at = started_at.trim();
    anyhow::ensure!(pgid > 0 && !started_at.is_empty(), "ps returned incomplete process identity");
    Ok((pgid, started_at.to_string()))
}

fn record_dispatch(store: &Store, log: &EventLog, dispatch: &DispatchRecord) -> Result<()> {
    store.create_dispatch(dispatch)?;

    log.record(&LogEntry {
        timestamp: now_iso(),
        run_id: dispatch.run_id.clone(),
        dispatch_id: Some(dispatch.id.clone()),
        agent: Some(dispatch.role.clone()),
        event: events::AGENT_ENTER.to_string(),
        details: Some(serde_json::json!({"worktree": dispatch.worktree, "backend": dispatch.backend, "trust_warning": dispatch.trust_warning})),
    })?;

    Ok(())
}

/// Starts a prepared Dispatch with the same session name and environment as a regular launch.
pub fn start_dispatch(
    env: &dyn Environment,
    run: &RunRecord,
    dispatch: &DispatchRecord,
    dispatch_dir: &Path,
) -> Result<()> {
    let session = Tmux::session_name(&dispatch.hash_id(run));
    let mut env_vars = vec![
        ("OAT_RUN_ID".to_string(), run.id.clone()),
        ("OAT_DISPATCH_ID".to_string(), dispatch.id.clone()),
        ("OAT_WORKTREE".to_string(), dispatch.worktree.clone()),
        (
            "OAT_DISPATCH_DIR".to_string(),
            dispatch_dir.to_string_lossy().to_string(),
        ),
    ];
    if let Some(m) = &dispatch.model {
        env_vars.push(("OAT_MODEL".to_string(), m.clone()));
    }
    if let Some(e) = &dispatch.effort {
        env_vars.push(("OAT_EFFORT".to_string(), e.clone()));
    }
    env_vars.extend(session_environment(env));

    Tmux::from_env(env).start_session(
        &session,
        Path::new(&dispatch.worktree),
        &env_vars,
        &dispatch_dir.join("launch.sh").to_string_lossy(),
    )
}

/// Denies the `AskUserQuestion` tool inside the worktree, as hardening against a role trying
/// to ask a human through an interactive panel (ticket §4.5). A failure to write it is
/// hardening that did not apply, not a reason to fail the launch.
pub fn write_claude_local_settings(worktree: &Path) -> Result<()> {
    let dir = worktree.join(".claude");
    fs::create_dir_all(&dir)?;
    let path = dir.join("settings.local.json");
    let content = serde_json::json!({
        "permissions": {
            "deny": ["AskUserQuestion"]
        }
    });
    fs::write(&path, serde_json::to_string_pretty(&content)?)
        .map_err(|e| err(codes::INVALID_LOCAL_SETTINGS, e.to_string()))?;
    let _ = skills::append_local_exclude(worktree, ".claude/settings.local.json");
    Ok(())
}

